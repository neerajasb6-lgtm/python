from graphicsss import rectangle, circle
from graphics_3D import cuboid, sphere

print("\n Area of rectangle:", rectangle.area(5, 3))
print("Perimeter of rectangle:", rectangle.perimeter(5, 3))

print("\n \nArea of circle:", circle.area(4))
print("Perimeter of circle:", circle.perimeter(4))

print("\n \nArea of cuboid:", cuboid.area(3, 2, 4))
print("Perimeter of cuboid:", cuboid.perimeter(4, 3, 1))

print("\n \nArea of sphere:", sphere.area(3))
print("Perimeter of sphere:", sphere.perimeter(2))

